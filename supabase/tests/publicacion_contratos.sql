create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
grant usage on schema public, auth to authenticated, anon, service_role;
grant execute on function auth.uid() to authenticated, anon;

create table public.roles (
  id bigint generated by default as identity primary key,
  codigo text unique not null,
  nombre text,
  ver_todo boolean default false
);
create table public.usuarios (
  id uuid primary key,
  auth_user_id uuid unique references auth.users(id),
  apellido text,
  nombre text
);
create table public.usuario_roles (usuario_id uuid, rol_id bigint references public.roles(id));
create function public.has_role_code(p_codigo text) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.usuario_roles ur
    join public.roles r on r.id = ur.rol_id
    left join public.usuarios u on u.id = ur.usuario_id
    where (ur.usuario_id = auth.uid() or u.auth_user_id = auth.uid())
      and r.codigo = p_codigo
  );
$$;
create function public.has_role(p_codigo text) returns boolean language sql stable as $$
  select public.has_role_code(p_codigo);
$$;
create function public.is_rrhh() returns boolean language sql stable as $$ select false; $$;
create function public.can_francos_read() returns boolean language sql stable as $$
  select public.has_role_code('FRANCOS_LECTURA');
$$;
create function public.can_horas_write() returns boolean language sql stable as $$
  select public.has_role_code('HORAS_CARGA');
$$;

create table public.personas (
  dni bigint primary key, apellido text not null, nombre text not null,
  legajo integer, fecha_nacimiento date, email text, telefono text,
  horario_rotativo boolean default false, created_by uuid, updated_by uuid,
  updated_at timestamp default now()
);
create table public.carreras (
  id bigint generated by default as identity primary key, nombre text unique
);
create table public.situacion_revista (
  id bigint generated by default as identity primary key, nombre text unique
);
create table public.persona_carreras (
  dni bigint primary key references public.personas(dni),
  carrera_id bigint references public.carreras(id)
);
create table public.persona_situacion_revista (
  dni bigint references public.personas(dni),
  situacion_id bigint references public.situacion_revista(id),
  primary key (dni, situacion_id)
);
create table public.persona_inactivo (
  dni bigint primary key references public.personas(dni), causa text,
  fecha date, observaciones text,
  constraint persona_baja_causa_check check (causa is not null)
);
create table public.horas_registros (
  id bigint generated by default as identity primary key,
  dni bigint, carrera_id bigint, tipo text,
  constraint ck_carrera_valida check (carrera_id in (1, 2, 3))
);
create table public.francos_movimientos (
  dni bigint, carrera_id bigint, minutos integer, anulado boolean default false
);
create view public.vw_listado_horas as
  select p.dni, p.apellido, p.nombre, pc.carrera_id, c.nombre as carrera
  from public.personas p join public.persona_carreras pc on pc.dni = p.dni
  join public.carreras c on c.id = pc.carrera_id;
create table public.suplencias (
  id bigint generated by default as identity primary key,
  suplente_dni bigint, suplente_apellido text, suplente_nombre text,
  suplente_servicio text, titular_dni bigint, titular_apellido text,
  titular_nombre text, titular_servicio text, motivo text, usuario_carga uuid
);
alter table public.suplencias enable row level security;
create view public.vw_suplencias_detalle_servicio with (security_invoker = true)
  as select * from public.suplencias;
grant select on public.suplencias, public.usuarios to authenticated;

