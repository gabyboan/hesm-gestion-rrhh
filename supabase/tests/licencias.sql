create function pg_temp.comprobar(ok boolean, mensaje text) returns void language plpgsql as $$
begin if ok is distinct from true then raise exception 'Falló: %', mensaje; end if; end;
$$;
create function pg_temp.rechazar(consulta text, estado text default '42501') returns void
language plpgsql security invoker as $$
begin
  begin
    execute consulta;
  exception when others then
    if sqlstate = estado then return; end if;
    raise;
  end;
  raise exception 'Se permitió una operación que debía rechazarse: %', consulta;
end;
$$;

