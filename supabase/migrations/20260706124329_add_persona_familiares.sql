create schema if not exists private;

create or replace function private.has_legajo_edit_role()
returns boolean
language sql
stable
security definer
set search_path to ''
as $function$
  select (select auth.uid()) is not null and exists (
    select 1
    from public.usuario_roles ur
    left join public.usuarios u on u.id = ur.usuario_id
    where (
        ur.usuario_id = (select auth.uid())
        or u.auth_user_id = (select auth.uid())
      )
      and ur.rol_id in (19, 20)
  );
$function$;

create table public.persona_familiares (
  id bigint generated by default as identity primary key,
  persona_dni bigint not null references public.personas(dni) on update cascade on delete cascade,
  apellido text not null check (btrim(apellido) <> ''),
  nombre text not null check (btrim(nombre) <> ''),
  fecha_nacimiento date,
  dni bigint check (dni is null or dni > 0),
  parentesco text not null check (btrim(parentesco) <> ''),
  created_by uuid not null default auth.uid(),
  updated_by uuid not null default auth.uid(),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint persona_familiares_fecha_nacimiento_valida
    check (fecha_nacimiento is null or fecha_nacimiento <= current_date)
);

comment on table public.persona_familiares is
  'Familiares de una persona compartidos con los flujos de parte medico de RRHH.';

create index persona_familiares_persona_dni_idx
  on public.persona_familiares (persona_dni);

create unique index persona_familiares_persona_dni_familiar_dni_uidx
  on public.persona_familiares (persona_dni, dni)
  where dni is not null;

alter table public.persona_familiares enable row level security;

create policy persona_familiares_select_legajo_editor
on public.persona_familiares for select to authenticated
using (private.has_legajo_edit_role());

create policy persona_familiares_insert_legajo_editor
on public.persona_familiares for insert to authenticated
with check (
  private.has_legajo_edit_role()
  and created_by = (select auth.uid())
  and updated_by = (select auth.uid())
);

create policy persona_familiares_update_legajo_editor
on public.persona_familiares for update to authenticated
using (private.has_legajo_edit_role())
with check (
  private.has_legajo_edit_role()
  and updated_by = (select auth.uid())
);

create policy persona_familiares_delete_legajo_editor
on public.persona_familiares for delete to authenticated
using (private.has_legajo_edit_role());

create or replace function public.rpc_medicos_familiares(p_dni bigint)
returns table (
  id bigint,
  apellido_nombre text,
  fecha_nacimiento date,
  dni bigint,
  edad integer,
  parentesco text
)
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
  if (select auth.uid()) is null then
    raise exception 'No autenticado.';
  end if;
  if not public.can_medicos_read() then
    raise exception 'Sin permiso para ver familiares en partes medicos.';
  end if;

  return query
  select
    pf.id,
    concat_ws(', ', pf.apellido, pf.nombre),
    pf.fecha_nacimiento,
    pf.dni,
    case
      when pf.fecha_nacimiento is null then null
      else extract(year from age(current_date, pf.fecha_nacimiento))::integer
    end,
    pf.parentesco
  from public.persona_familiares pf
  where pf.persona_dni = p_dni
  order by pf.apellido, pf.nombre, pf.id;
end;
$function$;

