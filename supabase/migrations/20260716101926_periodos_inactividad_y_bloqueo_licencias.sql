create function public.rpc_persona_inactivar(
  p_dni bigint,
  p_causa text,
  p_fecha_desde date,
  p_observaciones text default null
)
returns void
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  v_causa text := upper(trim(coalesce(p_causa, '')));
begin
  if (select auth.uid()) is null then
    raise exception 'No autenticado.';
  end if;

  if not private.has_legajo_edit_role() then
    raise exception 'Sin permiso para editar legajos.';
  end if;

  if p_dni is null
    or p_dni <= 0
    or not exists (select 1 from public.personas where dni = p_dni) then
    raise exception 'Persona inválida.';
  end if;

  if p_fecha_desde is null then
    raise exception 'La fecha de inicio es obligatoria.';
  end if;

  if v_causa not in (
    'JUBILADO', 'CESANTEADO', 'FALLECIDO', 'RENUNCIO',
    'PASE_FUERA', 'TRASLADO_FUERA', 'CORTE_SUPLENCIA', 'OTRO'
  ) then
    raise exception 'Causa de inactividad inválida.';
  end if;

  if exists (
    select 1
    from public.persona_inactividad_periodos
    where persona_dni = p_dni
      and fecha_hasta is null
  ) then
    raise exception 'La persona ya posee un período de inactividad abierto.';
  end if;

  insert into public.persona_inactividad_periodos (
    persona_dni, causa, fecha_desde, observaciones, created_by, updated_by
  )
  values (
    p_dni,
    v_causa,
    p_fecha_desde,
    nullif(btrim(p_observaciones), ''),
    (select auth.uid()),
    (select auth.uid())
  );

  insert into public.persona_inactivo (dni, causa, fecha, observaciones)
  values (p_dni, v_causa, p_fecha_desde, nullif(btrim(p_observaciones), ''));
end;
$function$;
create function public.rpc_persona_reactivar(
  p_dni bigint,
  p_fecha_hasta date default current_date
)
returns void
language plpgsql
security invoker
set search_path to ''
as $function$
declare
  v_fecha_desde date;
begin
  if (select auth.uid()) is null then
    raise exception 'No autenticado.';
  end if;

  if not private.has_legajo_edit_role() then
    raise exception 'Sin permiso para editar legajos.';
  end if;

  select fecha_desde
    into v_fecha_desde
  from public.persona_inactividad_periodos
  where persona_dni = p_dni
    and fecha_hasta is null
  for update;

  if not found then
    raise exception 'La persona no posee un período de inactividad abierto.';
  end if;

  if p_fecha_hasta is null or p_fecha_hasta < v_fecha_desde then
    raise exception 'La fecha de reactivación no puede ser anterior al inicio.';
  end if;

  update public.persona_inactividad_periodos
  set
    fecha_hasta = p_fecha_hasta,
    updated_at = now(),
    updated_by = (select auth.uid())
  where persona_dni = p_dni
    and fecha_hasta is null;

  delete from public.persona_inactivo where dni = p_dni;
end;
$function$;
create function public.validar_parte_medico_persona_activa()
returns trigger
language plpgsql
security invoker
set search_path to ''
as $function$
begin
  if new.anulado_at is null and exists (
    select 1
    from public.persona_inactividad_periodos pip
    where pip.persona_dni = new.dni
      and new.fecha >= pip.fecha_desde
      and (pip.fecha_hasta is null or new.fecha <= pip.fecha_hasta)
  ) then
    raise exception
      'No se puede cargar licencia: la persona estuvo inactiva en la fecha indicada.';
  end if;

  return new;
end;
$function$;
drop trigger if exists partes_medicos_validar_persona_activa
  on public.partes_medicos;
create trigger partes_medicos_validar_persona_activa
  before insert or update of dni, fecha, anulado_at
  on public.partes_medicos
  for each row
  execute function public.validar_parte_medico_persona_activa();
create or replace function public.rpc_medicos_personas(p_buscar text default null)
returns table (dni bigint, apellido text, nombre text, legajo integer)
language plpgsql
stable
security definer
set search_path to 'public'
as $function$
begin
  if (select auth.uid()) is null then
    raise exception 'No autenticado.';
  end if;

  if not public.can_medicos_read() then
    raise exception 'Sin permiso para ver partes medicos.';
  end if;

  return query
  select p.dni, p.apellido, p.nombre, p.legajo
  from public.personas p
  where p.legajo is not null
    and not exists (
      select 1 from public.persona_inactivo pi where pi.dni = p.dni
    )
    and (
      p_buscar is null
      or trim(p_buscar) = ''
      or p.dni::text ilike '%' || trim(p_buscar) || '%'
      or p.legajo::text ilike '%' || trim(p_buscar) || '%'
      or p.apellido ilike '%' || trim(p_buscar) || '%'
      or p.nombre ilike '%' || trim(p_buscar) || '%'
    )
  order by p.apellido, p.nombre, p.dni;
end;
$function$;
