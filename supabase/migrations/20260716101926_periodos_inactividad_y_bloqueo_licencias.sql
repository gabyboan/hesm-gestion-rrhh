-- Conserva persona_inactivo como estado vigente y agrega el historial de períodos.
alter table public.persona_inactivo
  drop constraint if exists persona_baja_causa_check;
alter table public.persona_inactivo
  add constraint persona_inactivo_causa_check
  check (causa in (
    'JUBILADO', 'CESANTEADO', 'FALLECIDO', 'RENUNCIO',
    'PASE_FUERA', 'TRASLADO_FUERA', 'CORTE_SUPLENCIA', 'OTRO'
  ));
create table public.persona_inactividad_periodos (
  id bigint generated by default as identity primary key,
  persona_dni bigint not null references public.personas(dni) on delete cascade,
  causa text not null check (causa in (
    'JUBILADO', 'CESANTEADO', 'FALLECIDO', 'RENUNCIO',
    'PASE_FUERA', 'TRASLADO_FUERA', 'CORTE_SUPLENCIA', 'OTRO'
  )),
  fecha_desde date not null,
  fecha_hasta date,
  observaciones text,
  created_at timestamp without time zone not null default now(),
  updated_at timestamp without time zone not null default now(),
  created_by uuid,
  updated_by uuid,
  check (fecha_hasta is null or fecha_hasta >= fecha_desde)
);
create unique index persona_inactividad_periodos_abierto_uidx
  on public.persona_inactividad_periodos (persona_dni)
  where fecha_hasta is null;
create index persona_inactividad_periodos_persona_fechas_idx
  on public.persona_inactividad_periodos (persona_dni, fecha_desde desc);
-- Preserva como período abierto todo inactivo que ya existía antes de esta migración.
insert into public.persona_inactividad_periodos (
  persona_dni, causa, fecha_desde, observaciones
)
select
  pi.dni,
  pi.causa,
  coalesce(pi.fecha, current_date),
  pi.observaciones
from public.persona_inactivo pi
where not exists (
  select 1
  from public.persona_inactividad_periodos pip
  where pip.persona_dni = pi.dni
    and pip.fecha_hasta is null
);
alter table public.persona_inactividad_periodos enable row level security;
grant select, insert, update, delete
