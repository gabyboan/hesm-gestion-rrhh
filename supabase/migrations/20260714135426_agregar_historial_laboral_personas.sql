-- Conserva eventos historicos sin confundirlos con el estado actual de inactividad.
create table public.persona_historial_laboral (
  id bigint generated by default as identity primary key,
  persona_dni bigint not null references public.personas(dni) on delete cascade,
  tipo text not null check (tipo in (
    'PASE', 'TRASLADO', 'CORTE', 'JUBILACION', 'FALLECIMIENTO',
    'RENUNCIA', 'CESANTIA', 'OTRO'
  )),
  fecha date,
  detalle text,
  origen_hoja text not null,
  origen_fila integer,
  datos_origen jsonb not null default '{}'::jsonb,
  created_at timestamp without time zone not null default now(),
  unique (persona_dni, origen_hoja, origen_fila)
);
create index persona_historial_laboral_persona_fecha_idx
  on public.persona_historial_laboral (persona_dni, fecha desc nulls last);
alter table public.persona_historial_laboral enable row level security;
grant select, insert, update, delete on table public.persona_historial_laboral to authenticated;
grant usage, select on sequence public.persona_historial_laboral_id_seq to authenticated;
create policy persona_historial_laboral_select
on public.persona_historial_laboral
for select to authenticated
using ((select private.has_legajo_edit_role()));
create policy persona_historial_laboral_insert
on public.persona_historial_laboral
for insert to authenticated
with check ((select private.has_legajo_edit_role()));
create policy persona_historial_laboral_update
on public.persona_historial_laboral
for update to authenticated
using ((select private.has_legajo_edit_role()))
with check ((select private.has_legajo_edit_role()));
create policy persona_historial_laboral_delete
on public.persona_historial_laboral
for delete to authenticated
using ((select private.has_legajo_edit_role()));
