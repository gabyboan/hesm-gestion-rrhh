-- Domicilios historicos y estructurados. Los IDs/nombres provienen de API Georef.
alter table public.personas
  drop column if exists domicilio;
create table public.persona_domicilios (
  id bigint generated by default as identity primary key,
  persona_dni bigint not null references public.personas(dni) on delete cascade,
  calle text,
  numero text,
  barrio text,
  manzana text,
  lote text,
  monoblock text,
  piso text,
  departamento text,
  referencias text,
  otros_datos text,
  provincia_georef_id text,
  provincia_nombre text,
  localidad_georef_id text,
  localidad_nombre text,
  vigente_desde date not null default current_date,
  vigente_hasta date,
  created_at timestamp without time zone not null default now(),
  updated_at timestamp without time zone not null default now(),
  created_by uuid,
  updated_by uuid,
  check (vigente_hasta is null or vigente_hasta >= vigente_desde)
);
create unique index persona_domicilios_unico_vigente_idx
  on public.persona_domicilios (persona_dni)
  where vigente_hasta is null;
create index persona_domicilios_persona_vigencia_idx
  on public.persona_domicilios (persona_dni, vigente_desde desc);
alter table public.persona_domicilios enable row level security;
grant select, insert, update, delete on table public.persona_domicilios to authenticated;
grant usage, select on sequence public.persona_domicilios_id_seq to authenticated;
create policy persona_domicilios_select
on public.persona_domicilios for select to authenticated
using ((select private.has_legajo_edit_role()));
create policy persona_domicilios_insert
on public.persona_domicilios for insert to authenticated
with check ((select private.has_legajo_edit_role()));
create policy persona_domicilios_update
on public.persona_domicilios for update to authenticated
using ((select private.has_legajo_edit_role()))
with check ((select private.has_legajo_edit_role()));
create policy persona_domicilios_delete
on public.persona_domicilios for delete to authenticated
using ((select private.has_legajo_edit_role()));
