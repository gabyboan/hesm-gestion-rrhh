-- Normaliza identificadores numericos y el catalogo de sexo antes de cargar datos.
create table public.sexos (
  id bigint generated by default as identity primary key,
  nombre text not null unique
);
insert into public.sexos (nombre)
values ('Masculino'), ('Femenino');
alter table public.sexos enable row level security;
grant select on table public.sexos to authenticated;
create policy sexos_select_authenticated
on public.sexos
for select
to authenticated
using ((select auth.uid()) is not null);
alter table public.personas
  alter column reloj type integer using nullif(regexp_replace(reloj, '[^0-9]', '', 'g'), '')::integer,
  alter column cuil type bigint using nullif(regexp_replace(cuil, '[^0-9]', '', 'g'), '')::bigint,
  alter column numero_contacto type bigint using nullif(regexp_replace(numero_contacto, '[^0-9]', '', 'g'), '')::bigint,
  drop column sexo,
  add column sexo_id bigint references public.sexos(id);
alter table public.personas
  add constraint personas_reloj_positivo check (reloj is null or reloj > 0),
  add constraint personas_cuil_11_digitos check (cuil is null or cuil between 10000000000 and 99999999999),
  add constraint personas_numero_contacto_positivo check (numero_contacto is null or numero_contacto > 0);
